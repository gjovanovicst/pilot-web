/**
 * Minimal HTML escaping helper for the markup components in this repository.
 * Attribute values are always double quoted, so the double quote is escaped too.
 */
export function escapeHtml(value: string): string {
  return value
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;')
    .replaceAll("'", '&#x27;');
}
